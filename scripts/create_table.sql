CREATE TABLE T_COLHEITA_CANA (
    ID_COLHEITA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TALHAO             VARCHAR2(30)  NOT NULL,
    DATA_COLHEITA      DATE          NOT NULL,
    TIPO_COLHEITA      VARCHAR2(10)  NOT NULL,
    COLHEDORA          VARCHAR2(30),
    AREA_HA            NUMBER(10,2)  NOT NULL,
    PROD_ESTIMADA_T_HA NUMBER(10,2)  NOT NULL,
    TONELADAS_COLHIDAS NUMBER(12,2)  NOT NULL,
    VELOCIDADE_KMH     NUMBER(5,2),
    ALTURA_CORTE_CM    NUMBER(5,2),
    PERDA_T            NUMBER(12,2)  NOT NULL,
    PERDA_PERC         NUMBER(5,2)   NOT NULL,
    PERDA_RS           NUMBER(14,2)  NOT NULL,
    CLASSIFICACAO      VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_COLHEITA_CANA PRIMARY KEY (ID_COLHEITA),
    CONSTRAINT CK_TIPO_COLHEITA CHECK (TIPO_COLHEITA IN ('MANUAL', 'MECANIZADA')),
    CONSTRAINT CK_CLASSIFICACAO CHECK (CLASSIFICACAO IN ('ACEITAVEL', 'ATENCAO', 'CRITICA')),
    CONSTRAINT CK_AREA_POSITIVA CHECK (AREA_HA > 0)
);

