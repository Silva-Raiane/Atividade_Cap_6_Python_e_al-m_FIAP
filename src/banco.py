"""
Conexão e operações (CRUD) no banco de dados Oracle da FIAP.

Usuário e senha NÃO ficam no código: são lidos de variáveis de ambiente
(nomes definidos no config.json). Se não existirem, o programa pergunta.
"""

import getpass
import os

import oracledb

SQL_CRIAR_TABELA = """
CREATE TABLE T_COLHEITA_CANA (
    ID_COLHEITA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TALHAO             VARCHAR2(30)  NOT NULL,
    DATA_COLHEITA      DATE          NOT NULL,
    TIPO_COLHEITA      VARCHAR2(10)  NOT NULL,
    COLHEDORA          VARCHAR2(30),
    AREA_HA            NUMBER(10,2)  NOT NULL,
    PROD_ESTIMADA_T_HA NUMBER(10,2)  NOT NULL,
    TONELADAS_COLHIDAS NUMBER(12,2)  NOT NULL,
    VELOCIDADE_KMH     NUMBER(5,2),
    ALTURA_CORTE_CM    NUMBER(5,2),
    PERDA_T            NUMBER(12,2)  NOT NULL,
    PERDA_PERC         NUMBER(5,2)   NOT NULL,
    PERDA_RS           NUMBER(14,2)  NOT NULL,
    CLASSIFICACAO      VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_COLHEITA_CANA PRIMARY KEY (ID_COLHEITA),
    CONSTRAINT CK_TIPO_COLHEITA CHECK (TIPO_COLHEITA IN ('MANUAL', 'MECANIZADA')),
    CONSTRAINT CK_CLASSIFICACAO CHECK (CLASSIFICACAO IN ('ACEITAVEL', 'ATENCAO', 'CRITICA')),
    CONSTRAINT CK_AREA_POSITIVA CHECK (AREA_HA > 0)
)"""

# Tupla com a ordem das colunas: usada tanto no SELECT quanto para montar os dicionários
COLUNAS = ("id_colheita", "talhao", "data_colheita", "tipo_colheita", "colhedora",
           "area_ha", "prod_estimada_t_ha", "toneladas_colhidas", "velocidade_kmh",
           "altura_corte_cm", "perda_t", "perda_perc", "perda_rs", "classificacao")

COLUNAS_GRAVACAO = COLUNAS[1:]  # todas menos o ID, que o Oracle gera


def obter_credenciais(config_oracle: dict) -> tuple:
    """Busca usuário/senha nas variáveis de ambiente; se faltar, pergunta."""
    usuario = os.getenv(config_oracle["usuario_env"])
    senha = os.getenv(config_oracle["senha_env"])
    if not usuario:
        usuario = input("Usuário Oracle (ex.: RM123456): ").strip()
    if not senha:
        senha = getpass.getpass("Senha Oracle: ")
    return usuario, senha


def conectar(config_oracle: dict):
    """Abre a conexão com o Oracle. Devolve a conexão ou None se falhar."""
    usuario, senha = obter_credenciais(config_oracle)
    try:
        conexao = oracledb.connect(user=usuario, password=senha, dsn=config_oracle["dsn"],
                                   tcp_connect_timeout=15)
        return conexao
    except (oracledb.Error, OSError) as erro:  # OSError cobre falhas de rede/DNS
        print(f"  ✖ Não foi possível conectar ao Oracle: {erro}")
        return None


def criar_tabela_se_nao_existir(conexao) -> None:
    """Procedimento: cria a T_COLHEITA_CANA na primeira execução."""
    with conexao.cursor() as cursor:
        cursor.execute("SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = 'T_COLHEITA_CANA'")
        if cursor.fetchone()[0] == 0:
            cursor.execute(SQL_CRIAR_TABELA)
            conexao.commit()
            print("  ✔ Tabela T_COLHEITA_CANA criada no Oracle.")


def inserir_colheita(conexao, colheita: dict) -> int:
    """Insere uma colheita e devolve o ID gerado pelo Oracle."""
    colunas = ", ".join(c.upper() for c in COLUNAS_GRAVACAO)
    parametros = ", ".join(f":{c}" for c in COLUNAS_GRAVACAO)
    sql = f"INSERT INTO T_COLHEITA_CANA ({colunas}) VALUES ({parametros}) " \
          f"RETURNING ID_COLHEITA INTO :novo_id"
    with conexao.cursor() as cursor:
        novo_id = cursor.var(oracledb.NUMBER)
        valores = {c: colheita.get(c) for c in COLUNAS_GRAVACAO}
        valores["novo_id"] = novo_id
        cursor.execute(sql, valores)
        conexao.commit()
        return int(novo_id.getvalue()[0])


def listar_colheitas(conexao) -> list:
    """Carrega todas as colheitas do banco como lista de dicionários."""
    sql = f"SELECT {', '.join(c.upper() for c in COLUNAS)} FROM T_COLHEITA_CANA " \
          f"ORDER BY DATA_COLHEITA, ID_COLHEITA"
    with conexao.cursor() as cursor:
        cursor.execute(sql)
        registros = []
        for linha in cursor.fetchall():
            registro = dict(zip(COLUNAS, linha))
            registro["data_colheita"] = registro["data_colheita"].date()
            for campo in ("area_ha", "prod_estimada_t_ha", "toneladas_colhidas", "velocidade_kmh",
                          "altura_corte_cm", "perda_t", "perda_perc", "perda_rs"):
                if registro[campo] is not None:
                    registro[campo] = float(registro[campo])
            registros.append(registro)
        return registros


def atualizar_colheita(conexao, id_colheita: int, colheita: dict) -> bool:
    """Atualiza todos os campos de uma colheita. Devolve True se achou o ID."""
    atribuicoes = ", ".join(f"{c.upper()} = :{c}" for c in COLUNAS_GRAVACAO)
    sql = f"UPDATE T_COLHEITA_CANA SET {atribuicoes} WHERE ID_COLHEITA = :id_colheita"
    with conexao.cursor() as cursor:
        valores = {c: colheita.get(c) for c in COLUNAS_GRAVACAO}
        valores["id_colheita"] = id_colheita
        cursor.execute(sql, valores)
        conexao.commit()
        return cursor.rowcount > 0


def excluir_colheita(conexao, id_colheita: int) -> bool:
    """Exclui uma colheita pelo ID. Devolve True se removeu."""
    with conexao.cursor() as cursor:
        cursor.execute("DELETE FROM T_COLHEITA_CANA WHERE ID_COLHEITA = :id", {"id": id_colheita})
        conexao.commit()
        return cursor.rowcount > 0
